#!/usr/bin/env python3
"""Prepare completed study evidence as an RO-Crate 1.3-targeted package.

Ensures strict provenance, hash verification for inputs, outputs, and code snapshots.
Follows the Research Companion and RO-Crate 1.3 specifications.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import posixpath
import re
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

PLUGIN_ROOT = Path(__file__).resolve().parents[3]
if str(PLUGIN_ROOT) not in sys.path:
    sys.path.insert(0, str(PLUGIN_ROOT))
from references.publication_contract import checked_path, validate_run, verify_file, yaml_load

CRATE_SPEC = "https://w3id.org/ro/crate/1.3"
CRATE_CONTEXT = "https://w3id.org/ro/crate/1.3/context"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def safe_path(base: Path, rel: str | Path) -> Path:
    p = (base / rel).resolve()
    base_res = base.resolve()
    if p != base_res and base_res not in p.parents:
        raise ValueError(f"Path traversal detected: {rel}")
    return p


def reserve_sibling_path(parent: Path, prefix: str) -> Path:
    reserved = Path(tempfile.mkdtemp(prefix=prefix, dir=parent))
    reserved.rmdir()
    return reserved


def remove_package_path(path: Path) -> None:
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif path.exists() or path.is_symlink():
        path.unlink()


def is_recognized_crate(path: Path) -> bool:
    metadata_path = path / "ro-crate-metadata.json"
    readme_path = path / "README.md"
    if not metadata_path.is_file() or not readme_path.is_file():
        return False
    try:
        crate = json.loads(metadata_path.read_text(encoding="utf-8"))
        graph = crate.get("@graph") if isinstance(crate, dict) else None
        readme = readme_path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return False
    if not isinstance(crate, dict) or not isinstance(graph, list) or len(graph) < 2:
        return False
    descriptor, root = graph[0], graph[1]
    if not isinstance(descriptor, dict) or not isinstance(root, dict):
        return False
    conforms_to = descriptor.get("conformsTo")
    return (
        crate.get("@context") == CRATE_CONTEXT
        and descriptor.get("@id") == "ro-crate-metadata.json"
        and isinstance(conforms_to, dict)
        and conforms_to.get("@id") == CRATE_SPEC
        and root.get("@id") == "./"
        and root.get("@type") == "Dataset"
        and "Generated by `ro-crate-research`" in readme
    )


def reject_symlink_components_below(path: Path, trusted_roots: list[Path]) -> None:
    supplied = path.absolute()
    for root in trusted_roots:
        resolved_root = root.resolve()
        try:
            relative = supplied.relative_to(resolved_root)
        except ValueError:
            continue
        current = resolved_root
        for part in relative.parts:
            current = current / part
            if current.is_symlink():
                raise ValueError(f"Symlink package destination is not allowed below trusted root: {current}")
    if supplied.is_symlink():
        raise ValueError(f"Symlink package destination is not allowed: {supplied}")


def publish_package(staging: Path, destination: Path) -> None:
    backup = reserve_sibling_path(destination.parent, f".{destination.name}.backup-") if destination.exists() else None
    try:
        if backup is not None:
            os.replace(destination, backup)
        os.replace(staging, destination)
    except BaseException as exc:  # aqg: top-level boundary - package replacement rollback must preserve prior package data, including interruption
        moved_old = backup is not None and backup.exists()
        stage_published = not staging.exists() and destination.exists()
        if moved_old:
            try:
                if destination.exists():
                    remove_package_path(destination)
                os.replace(backup, destination)
            except BaseException as restore_exc:  # aqg: top-level boundary - package recovery failure leaves prior data at recovery path
                raise RuntimeError(f"Package replacement failed and prior package remains at recovery path {backup}: {restore_exc}") from exc
        elif stage_published:
            remove_package_path(destination)
        raise
    else:
        if backup is not None and backup.exists():
            shutil.rmtree(backup, ignore_errors=True)


def load_yaml_file(path: Path) -> dict[str, Any]:
    data = yaml_load(path)
    if not isinstance(data, dict):
        raise ValueError(f"Expected a YAML mapping in {path}")
    return data


def read_question(study_root: Path) -> str:
    reasoning_path = study_root / "spec" / "reasoning.md"
    if not reasoning_path.is_file():
        return f"Study: {study_root.name}"
    content = reasoning_path.read_text(encoding="utf-8")
    m = re.search(r"##\s*1\.\s*Scientific Question\s*\n+(.*?)(?=\n##|\Z)", content, re.DOTALL)
    if m and m.group(1).strip():
        return m.group(1).strip()
    lines = [line.strip() for line in content.splitlines() if line.strip() and not line.startswith("#")]
    return lines[0] if lines else f"Study: {study_root.name}"


def copy_and_verify(source: Path, target: Path, expected_hash: str | None = None) -> str:
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink():
        raise ValueError(f"Symlink destination not allowed: {target}")
    if target.exists():
        raise ValueError(f"Duplicate package destination ID: {target}")
    shutil.copyfile(source, target)
    actual_hash = sha256_file(target)
    if expected_hash is not None and actual_hash != expected_hash:
        raise ValueError(f"Hash mismatch on copying {source} -> {target}: expected {expected_hash}, got {actual_hash}")
    return actual_hash


def validate_crate(crate_root: Path) -> None:
    meta_path = crate_root / "ro-crate-metadata.json"
    if not meta_path.is_file():
        raise ValueError("RO-CRATE_INVALID: ro-crate-metadata.json missing")
    crate = json.loads(meta_path.read_text(encoding="utf-8"))
    graph = crate.get("@graph")
    if crate.get("@context") != CRATE_CONTEXT or not isinstance(graph, list) or len(graph) < 2:
        raise ValueError("RO-CRATE_INVALID: missing versioned context or graph")
    if (
        graph[0].get("@id") != "ro-crate-metadata.json"
        or graph[0].get("conformsTo", {}).get("@id") != CRATE_SPEC
        or graph[0].get("about", {}).get("@id") != "./"
    ):
        raise ValueError("RO-CRATE_INVALID: metadata descriptor does not conform to root spec")
    if graph[1].get("@id") != "./" or graph[1].get("@type") != "Dataset":
        raise ValueError("RO-CRATE_INVALID: root data entity is missing or not a Dataset")

    for entity in graph[2:]:
        ent_type = entity.get("@type")
        types = ent_type if isinstance(ent_type, list) else [ent_type]
        if "File" in types:
            rel_path = entity.get("@id")
            if not rel_path:
                raise ValueError("RO-CRATE_INVALID: file entity missing @id")
            file_path = safe_path(crate_root, rel_path)
            if not file_path.is_file():
                raise ValueError(f"RO-CRATE_INVALID: missing packaged file {rel_path}")
            expected = entity.get("sha256")
            if expected and sha256_file(file_path) != expected:
                raise ValueError(f"RO-CRATE_INVALID: packaged file hash mismatch: {rel_path}")


def package_study(
    study_root: Path,
    run_ids: list[str],
    output_dir: Path | None = None,
    replace_package: bool = False,
    formats: list[str] | None = None,
    output_scope: str | None = None,
    preview: bool = False,
    author: str | None = None,
    license: str | None = None,
    description: str | None = None,
    include_inputs: bool = True,
    project_root: Path | None = None,
) -> Path | dict[str, Any]:
    study_root = study_root.resolve()
    if not license or not license.strip():
        raise ValueError("RO-Crate 1.3 requires an explicitly supplied --license; provide the applicable license identifier or URL")
    if output_scope not in {"accepted-only", "all-selected"}:
        raise ValueError("An explicit output_scope is required: 'accepted-only' or 'all-selected'")
    if project_root is None:
        raise ValueError("Explicit project_root is required to validate declared input paths")
    project_root = project_root.resolve()
    if len(set(run_ids)) != len(run_ids):
        raise ValueError("Duplicate run IDs are not allowed in a package selection")
    if not study_root.is_dir():
        raise FileNotFoundError(f"Study root not found: {study_root}")

    destination_input = output_dir or (study_root / "results" / "package")
    reject_symlink_components_below(destination_input, [study_root, project_root])
    destination = destination_input.resolve()
    protected = [*(study_root / name for name in ("spec", "plans", "scripts", "runs")), project_root / "data" / "raw"]
    overlaps_protected = any(
        destination == root or root in destination.parents or destination in root.parents
        for root in (path.resolve() for path in protected)
    )
    overlaps_protected = overlaps_protected or destination == study_root or destination in study_root.parents
    results_root = (study_root / "results").resolve()
    artifacts_root = results_root / "artifacts"
    if overlaps_protected or destination == results_root or (results_root / "RESULT.md") == destination or (results_root / "evidence-ledger.json") == destination or destination == artifacts_root or artifacts_root in destination.parents or destination in artifacts_root.parents:
        raise ValueError(f"Package destination overlaps protected study content: {destination}")
    if destination.exists() and not replace_package and not preview:
        raise FileExistsError(f"Package destination already exists: {destination}. Pass replace_package=True to replace.")
    if destination.exists() and not destination.is_dir():
        raise ValueError(f"Existing package destination is not a directory: {destination}")
    allowed_package_destination = destination == (study_root / "results" / "package").resolve()
    if destination.exists() and replace_package and not allowed_package_destination and not is_recognized_crate(destination):
        raise ValueError(f"Refusing to replace existing custom output directory that is not a recognized RO-Crate: {destination}")

    # Normalize formats filter if provided
    allowed_exts = {f.lower() if f.startswith(".") else f".{f.lower()}" for f in formats} if formats else None

    # Load the disposition ledger for the chosen output scope.
    accepted_paths: set[tuple[str, str]] | None = None
    accepted_bindings: dict[str, str] = {}
    accepted_hashes: dict[tuple[str, str], str] = {}
    output_dispositions: dict[tuple[str, str], str] = {}
    output_ledger_records: dict[tuple[str, str], dict[str, Any]] = {}
    ledger_run_bindings: dict[str, str] = {}
    ledger_file: Path | None = None
    if output_scope in {"accepted-only", "all-selected"}:
        ledger_file = study_root / "results" / "evidence-ledger.json"
        if not ledger_file.is_file():
            raise FileNotFoundError(f"evidence-ledger.json not found in {study_root / 'results'}. Run compose-research first.")
        ledger = json.loads(ledger_file.read_text(encoding="utf-8"))
        if not isinstance(ledger, dict) or not isinstance(ledger.get("records"), list):
            raise ValueError("Evidence ledger has an unsupported shape")
        if any(not isinstance(r, dict) for r in ledger["records"]):
            raise ValueError("Evidence ledger contains a malformed record")
        if output_scope == "accepted-only":
            run_entries = ledger.get("runs")
            if not isinstance(run_entries, list) or any(not isinstance(item, dict) for item in run_entries):
                raise ValueError("Accepted-only output scope requires evidence-ledger run bindings")
            for entry in run_entries:
                rid, digest = entry.get("run_id"), entry.get("lock_sha256")
                if not isinstance(rid, str) or not rid or not isinstance(digest, str) or not digest:
                    raise ValueError("Evidence ledger run bindings must include run_id and lock_sha256")
                if rid in ledger_run_bindings:
                    raise ValueError(f"Duplicate evidence ledger run binding: {rid}")
                ledger_run_bindings[rid] = digest
            accepted_records = [r for r in ledger["records"] if r.get("disposition") == "ACCEPTED"]
            if any(not r.get("run_id") or not r.get("path") or not r.get("lock_sha256") or not r.get("sha256") for r in accepted_records):
                raise ValueError("Accepted ledger records must bind run_id, path, lock_sha256, and sha256")
            accepted_paths = set()
            for record in accepted_records:
                binding = (record["run_id"], record["path"])
                if binding in output_dispositions:
                    raise ValueError(f"Duplicate accepted ledger output binding: {record['run_id']}/{record['path']}")
                prior_digest = accepted_bindings.setdefault(record["run_id"], record["lock_sha256"])
                if prior_digest != record["lock_sha256"]:
                    raise ValueError(f"Conflicting accepted ledger bindings for run {record['run_id']}")
                accepted_paths.add(binding)
                accepted_hashes[binding] = record["sha256"]
                output_dispositions[binding] = "ACCEPTED"
        else:
            valid_dispositions = {"ACCEPTED", "REJECTED", "AMBIGUOUS", "SUPERSEDED"}
            run_entries = ledger.get("runs")
            if not isinstance(run_entries, list) or any(not isinstance(item, dict) for item in run_entries):
                raise ValueError("All-selected output scope requires evidence-ledger run bindings")
            for entry in run_entries:
                rid, digest = entry.get("run_id"), entry.get("lock_sha256")
                if not isinstance(rid, str) or not rid or not isinstance(digest, str) or not digest:
                    raise ValueError("Evidence ledger run bindings must include run_id and lock_sha256")
                if rid in ledger_run_bindings:
                    raise ValueError(f"Duplicate evidence ledger run binding: {rid}")
                ledger_run_bindings[rid] = digest
            for record in ledger["records"]:
                rid, path, digest, output_hash = (record.get(key) for key in ("run_id", "path", "lock_sha256", "sha256"))
                disposition = record.get("disposition")
                if not all(isinstance(value, str) and value for value in (rid, path, digest, output_hash)):
                    raise ValueError("All-selected evidence ledger records must bind run_id, path, lock_sha256, and sha256")
                if disposition not in valid_dispositions:
                    raise ValueError(f"Unsupported or missing output disposition for {rid}/{path}: {disposition!r}")
                binding = (rid, path)
                if binding in output_dispositions:
                    raise ValueError(f"Duplicate evidence ledger output binding: {rid}/{path}")
                output_dispositions[binding] = disposition
                output_ledger_records[binding] = record

    # 1. Load run locks
    locks = []
    for rid in run_ids:
        lock_data, lock_path, lock_digest = validate_run(study_root, rid, project_root, verify_inputs=include_inputs)
        for inp in lock_data["inputs"]:
            for file_info in inp["files"]:
                input_path = checked_path(project_root, file_info["path"], allow_absolute=True)
                if destination == input_path or destination in input_path.parents:
                    raise ValueError(f"Package destination aliases selected raw input evidence: {input_path}")
        if output_scope == "accepted-only" and ledger_run_bindings.get(rid) != lock_digest:
            raise ValueError(f"Stale evidence ledger binding for run {rid}")
        if output_scope == "all-selected":
            if ledger_run_bindings.get(rid) != lock_digest:
                raise ValueError(f"Stale evidence ledger binding for run {rid}")
            for output in lock_data["outputs"]:
                output_path = output["path"]
                if output["role"] == "log" or (allowed_exts and Path(output_path).suffix.lower() not in allowed_exts):
                    continue
                record = output_ledger_records.get((rid, output_path))
                if record is None:
                    raise ValueError(f"Evidence ledger has no disposition for selected output {rid}/{output_path}")
                if record["lock_sha256"] != lock_digest:
                    raise ValueError(f"Stale evidence ledger binding for run {rid}")
                if record["sha256"] != output["sha256"]:
                    raise ValueError(f"Evidence ledger output hash mismatch for {rid}/{output_path}")
        if output_scope == "accepted-only":
            lock_hashes = {item["path"]: item["sha256"] for item in lock_data["outputs"]}
            for accepted_run, accepted_path in accepted_paths or ():
                if accepted_run == rid and lock_hashes.get(accepted_path) != accepted_hashes[(accepted_run, accepted_path)]:
                    raise ValueError(f"Accepted evidence ledger digest does not match run {rid}: {accepted_path}")
        locks.append((lock_data, lock_path, lock_digest))

    if output_scope == "accepted-only" and not any(rid in run_ids for rid, _ in (accepted_paths or set())):
        raise ValueError("No ACCEPTED outputs are selected; accepted-only packaging would contain provenance only")

    question = description or read_question(study_root)

    # One validated selection drives both preview and package assembly.
    inventory: list[dict[str, Any]] = []
    destinations: set[str] = set()

    def select(kind: str, run_id: str, source: Path, package_path: str, expected_hash: str, **metadata: Any) -> None:
        if "\\" in package_path:
            raise ValueError(f"Unsafe package destination ID: {package_path}")
        canonical = posixpath.normpath(package_path)
        if canonical in {"", ".", ".."} or canonical.startswith("../") or canonical.startswith("/"):
            raise ValueError(f"Unsafe package destination ID: {package_path}")
        if canonical in destinations:
            raise ValueError(f"Duplicate package destination ID: {canonical}")
        destinations.add(canonical)
        digest = verify_file(source, expected_hash, f"{kind} {run_id}")
        inventory.append({"kind": kind, "run_id": run_id, "source": source, "package_path": canonical, "sha256": digest, **metadata})

    for lock, lock_path, lock_digest in locks:
        rid = lock["run_id"]
        run_dir = study_root / "runs" / rid
        for out in lock["outputs"]:
            path_rel = out["path"]
            if out["role"] == "log" or (allowed_exts and Path(path_rel).suffix.lower() not in allowed_exts):
                continue
            if output_scope == "accepted-only" and accepted_paths is not None and (rid, path_rel) not in accepted_paths:
                continue
            source = checked_path(run_dir, path_rel)
            select("output", rid, source, f"outputs/{rid}/{path_rel}", out["sha256"], role=out["role"], name=Path(path_rel).name, relative_path=path_rel, disposition=output_dispositions[(rid, path_rel)])

        if include_inputs:
            for inp in lock["inputs"]:
                for file_info in inp["files"]:
                    source = checked_path(project_root, file_info["path"], allow_absolute=True)
                    project_relative = source.relative_to(project_root).as_posix()
                    select("input", rid, source, f"inputs/{rid}/{inp['object_id']}/{project_relative}", file_info["sha256"], role=inp["role"], name=source.name, source_path=project_relative)

        select("provenance", rid, lock_path, f"provenance/runs/{rid}/run.lock.yaml", lock_digest, name="run.lock.yaml")
        for field in ("plan", "input_manifest"):
            snapshot_rel = lock[field]["snapshot_path"]
            source = checked_path(study_root, snapshot_rel)
            select("provenance", rid, source, f"provenance/{snapshot_rel}", lock[field]["sha256"], name=Path(snapshot_rel).name)
        for code in lock["code"]["files"]:
            snapshot_rel = code["snapshot_path"]
            source = checked_path(study_root, snapshot_rel)
            rel = code["path"]
            select("code", rid, source, f"code/{rid}/{rel}", code["sha256"], name=Path(rel).name)

    if ledger_file is not None:
        select("provenance", study_root.name, ledger_file, "provenance/results/evidence-ledger.json", sha256_file(ledger_file), name="evidence-ledger.json")

    # If preview mode, output what would be included without assembling
    if preview:
        print("=== RO-CRATE PREVIEW (DRY-RUN) ===")
        print(f"Study: {study_root.name}")
        print(f"Destination: {destination}")
        print(f"Question / Description: {question}")
        if author:
            print(f"Author: {author}")
        if license:
            print(f"License: {license}")
        if allowed_exts:
            print(f"Formats Filter: {', '.join(sorted(allowed_exts))}")
        print(f"Output Scope: {output_scope}")

        outputs = [item for item in inventory if item["kind"] == "output"]
        print(f"Outputs to Package ({len(outputs)} files):")
        for item in outputs:
            print(f"  - [{Path(item['relative_path']).suffix.lower()}] {item['run_id']}/{item['relative_path']} ({item['source'].stat().st_size} bytes, sha256 {item['sha256']})")

        return {
            "study": study_root.name,
            "destination": str(destination),
            "output_scope": output_scope,
            "outputs_count": len(outputs),
            "outputs": [(item["run_id"], item["relative_path"], item["source"].stat().st_size, item["sha256"]) for item in outputs],
            "output_dispositions": {f"{item['run_id']}/{item['relative_path']}": item["disposition"] for item in outputs},
            "inventory": [{key: value for key, value in item.items() if key != "source"} for item in inventory],
            "inputs_included": include_inputs,
        }

    # 2. Stage beside the destination so publication and backup stay on its filesystem.
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=f".{destination.name}.staging-", dir=destination.parent) as tmp:
        staging = Path(tmp) / "crate"
        staging.mkdir()

        root_dataset: dict[str, Any] = {
            "@id": "./",
            "@type": "Dataset",
            "name": study_root.name,
            "description": question,
            "datePublished": datetime.now(timezone.utc).isoformat(),
            "hasPart": [],
        }
        if author:
            root_dataset["creator"] = {"@id": "#creator"}
        root_dataset["license"] = license.strip()
        root_dataset["additionalProperty"] = {"@id": "#output-scope"}

        graph: list[dict[str, Any]] = [
            {
                "@id": "ro-crate-metadata.json",
                "@type": "CreativeWork",
                "conformsTo": {"@id": CRATE_SPEC},
                "about": {"@id": "./"},
            },
            root_dataset,
        ]
        if author:
            graph.append({"@id": "#creator", "@type": "Person", "name": author})
        graph.append({"@id": "#output-scope", "@type": "PropertyValue", "name": "outputScope", "value": output_scope})

        for item in inventory:
            dest_rel = item["package_path"]
            digest = copy_and_verify(item["source"], safe_path(staging, dest_rel), item["sha256"])
            graph[1]["hasPart"].append({"@id": dest_rel})
            entity: dict[str, Any] = {"@id": dest_rel, "@type": ["File", "SoftwareSourceCode"] if item["kind"] == "code" else "File", "name": item["name"], "sha256": digest}
            if item["kind"] == "code":
                entity["programmingLanguage"] = "Python"
            elif item["kind"] in {"output", "input"}:
                entity["additionalProperty"] = []
                properties = [("sourceRun", item["run_id"]), ("role", item["role"])]
                if item["kind"] == "output":
                    properties.append(("disposition", item["disposition"]))
                for name, value in properties:
                    property_id = "#property-" + hashlib.sha256(f"{dest_rel}:{name}".encode()).hexdigest()
                    entity["additionalProperty"].append({"@id": property_id})
                    graph.append({"@id": property_id, "@type": "PropertyValue", "name": name, "value": value})
            graph.append(entity)

        # Write README.md
        readme_lines = [
            f"# RO-Crate: {study_root.name}",
            "",
            f"**Scientific Question**: {question}",
            "",
            "## Selected Runs",
            "",
        ]
        for rid in run_ids:
            readme_lines.append(f"- `{rid}`")
        readme_lines.extend([
            "",
            "## Output Dispositions",
            "",
            f"Output scope: {'accepted-only' if output_scope == 'accepted-only' else 'all selected outputs with explicit dispositions'}.",
            "",
            "| Run | Output | Disposition |",
            "|---|---|---|",
        ])
        output_items = [item for item in inventory if item["kind"] == "output"]
        if output_items:
            readme_lines.extend(f"| `{item['run_id']}` | `{item['relative_path']}` | {item['disposition']} |" for item in output_items)
        else:
            readme_lines.append("| — | No outputs selected | — |")
        readme_lines.extend([
            "",
            "## Metadata",
            "",
            "- Standard: RO-Crate 1.3 (independent validation not performed)",
            f"- Input scope: {'included' if include_inputs else 'excluded by request; outputs-only package'}",
            "- Descriptor: `ro-crate-metadata.json`",
            f"- Creator: {author or 'Unspecified'}",
            f"- License: {license or 'Unspecified'}",
            "- Generated by `ro-crate-research`",
        ])
        readme_path = staging / "README.md"
        readme_path.write_text("\n".join(readme_lines) + "\n", encoding="utf-8")
        graph[1]["hasPart"].append({"@id": "README.md"})
        graph.append({
            "@id": "README.md",
            "@type": "File",
            "name": "README.md",
            "sha256": sha256_file(readme_path),
        })

        # Write ro-crate-metadata.json
        crate_obj = {
            "@context": CRATE_CONTEXT,
            "@graph": graph,
        }
        (staging / "ro-crate-metadata.json").write_text(
            json.dumps(crate_obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )

        # Validate crate before finalizing
        validate_crate(staging)

        publish_package(staging, destination)

    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description="Package study results into an RO-Crate 1.3 bundle.")
    parser.add_argument("study_root", help="Path to study root directory")
    parser.add_argument("--project-root", required=True, help="Explicit project root used to resolve declared input paths")
    parser.add_argument("--run-id", action="append", required=True, dest="run_ids", help="Run ID(s) to include")
    parser.add_argument("--output-dir", help="Output package directory (default: results/package)")
    parser.add_argument("--replace-package", action="store_true", help="Replace existing package directory")
    parser.add_argument("--formats", help="Comma-separated file extensions to include (e.g. pdf,png,csv)")
    output_scope_group = parser.add_mutually_exclusive_group(required=True)
    output_scope_group.add_argument("--only-accepted", dest="output_scope", action="store_const", const="accepted-only", help="Only package ledger-bound outputs with ACCEPTED disposition")
    output_scope_group.add_argument("--include-all-selected-outputs", dest="output_scope", action="store_const", const="all-selected", help="Include every selected output with an explicit supported ledger disposition")
    parser.add_argument("--check", action="store_true", help="Preview crate contents and verify hashes without writing")
    parser.add_argument("--author", help="Author name to record in RO-Crate metadata")
    parser.add_argument("--license", required=True, help="Required explicit license identifier or URL; no default is assumed")
    parser.add_argument("--description", help="Description / abstract for RO-Crate metadata")
    parser.add_argument("--exclude-inputs", action="store_true", help="Explicitly omit raw inputs; produces an outputs-only package")

    args = parser.parse_args()
    try:
        out_dir = Path(args.output_dir) if args.output_dir else None
        formats = [f.strip() for f in args.formats.split(",")] if args.formats else None
        pkg_res = package_study(
            Path(args.study_root),
            args.run_ids,
            output_dir=out_dir,
            replace_package=args.replace_package,
            formats=formats,
            output_scope=args.output_scope,
            preview=args.check,
            author=args.author,
            license=args.license,
            description=args.description,
            include_inputs=not args.exclude_inputs,
            project_root=Path(args.project_root),
        )
        if args.check:
            print("RO-CRATE_CHECK_OK")
        else:
            print(f"PACKAGE_SUCCESS {pkg_res}")
        return 0
    except Exception as exc:
        print(f"PACKAGE_ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
